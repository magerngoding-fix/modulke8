import numpy as np

def regresi(x, y):
    """Curve fitting y = w0 + w1*x lewat normal equation (X^T X) w = X^T y."""
    X = np.column_stack([np.ones(len(x)), x])
    w = np.linalg.solve(X.T @ X, X.T @ y)
    y_hat = X @ w
    e = y - y_hat
    return X, w, y_hat, e

# Bagian 3: data (1,1), (2,3), (3,4)
x = np.array([1., 2., 3.]); y = np.array([1., 3., 4.])
X, w, P, e = regresi(x, y)
c1, c2 = X[:, 0], X[:, 1]
print("w =", w); print("P =", P); print("e =", e)
print("c1.e =", c1 @ e, " c2.e =", c2 @ e)

